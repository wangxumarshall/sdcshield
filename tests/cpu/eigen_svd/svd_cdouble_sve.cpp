/* Per-tier payload namespaces (svd_cdouble_sve_body.cpp). The EigenSVDTest
 * data type is itself Eigen-parameterised, so allocation/cleanup/run all live
 * in the variant TU; this dispatcher only sees void* — design §4.7.
 * The namespace block, the svd_tier_bits variable (tier chosen at init from
 * the chip maximum, re-checked at run from the worker's pinned VL — they must
 * agree: switching variants mid-test would reinterpret the Eigen objects
 * allocated by a different instantiation) and the joint-solver probe routing
 * (svd_solve_once: the probe executes that tier's fixed-width Eigen packets
 * on the init thread, whose VL is the framework-pinned control-thread tier —
 * the same tier make_data allocates for and test_run re-checks, so packet
 * width and executing VL always match) are all generated by
 * EIGEN_SVE_DECLARE_BODY_NS / EIGEN_SVE_DEFINE_DISPATCHERS in
 * sandstone_eigen_sve_dispatch.h (migrated there 2026-11-02; semantics
 * preserved verbatim). */
EIGEN_SVE_DECLARE_BODY_NS(svd);
EIGEN_SVE_DEFINE_DISPATCHERS(svd);

/* Runtime dimension mode: the template allocates and compares against
 * d->dim, which the CHILD test_init derives (knob/env > joint solver). */

/* Dimension bounds (measurement history: cortex x3b, VL=128 pinned, same
 * compile flags as this TU, 2026-09-19 — plan file
 * docs/superpowers/plans/2026-09-19-svd-cdouble-sve-mdim-5800.md):
 *
 *   MDIM_MIN  = 300: the NEON counterpart's parity point; the floor and
 *                    the joint-solver lo (quick mode collapses here).
 *   MDIM_MAX  = 6000: knob ceiling AND joint-solver hi (6000 alone
 *                    already busts the time budget; it exists for opt-in
 *                    experiments on faster hosts).
 *
 * Measured single-BDCSVD times on that host: 2400→40s, 3600→134s,
 * 4400→243s, 4800→322s, 5600→511s, 5800→563s, 6000→622s (~N³ scaling);
 * the old 4400 time cap and the 12x-of-16·N²-per-worker memory model were
 * superseded by the joint solver (child side: RSS_RATIO_TABLE
 * SDC_RSS_BDCSVD_C128 = 0.2055 KB/n²/thread measured differential
 * coefficient + the table-AR iteration budget; preinit side: the
 * t(N) = 243.4s·(N/4400)³ + 1s fit of those same points, still used for
 * the desired_duration upper bound below).
 */
#define MDIM_MIN 300
#define MDIM_MAX 6000

/*
 * preinit (runs once in the PARENT, before run_one_test computes
 * test_duration() — so writing test->desired_duration here is effective
 * for the very first run, unlike in test_init; same pattern as
 * ist_skip_preinit setting test->minimum_duration).
 *
 * P0-1 (spec §4.5, q2 invariant): the dimension itself is no longer sized
 * here — the child's test_init does that per NUMA node with the joint
 * solver, which also fixes exec_each_test children (their freshly-exec'd
 * image never ran this preinit, so the old parent-sized static arrived
 * un-initialised at 300). The preinit only writes an UPPER bound:
 *
 *   n_hi  = sqrt(budget650 / (workers × c_BDCSVD_C128)), clamped to
 *           [MDIM_MIN, MDIM_MAX] — the same four-source memory budget
 *           and RSS-table coefficient (sdc_rss_table_c(), not a literal —
 *           the table was re-calibrated once already: GEMM_F64
 *           0.0290→0.0315) the child's n_mem uses, with workers = the
 *           run's actual whole-machine worker count
 *           (sdc_total_threads(), available in preinit: commit_shmem()
 *           runs before test_preinit). The child's n_mem denominator is
 *           the same worker count scaled to its node
 *           (sdc_joint_dim_slice folds workers/total_cpus into
 *           node_cpus), so n_hi tracks it on every host class — not
 *           just the 127-worker reference the value was historically
 *           hard-coded to.
 *   auto:  dur = t(n_hi) × 0.95,  t(N) = 243.4s·(N/4400)³ + 1s  (x3b fit,
 *           within ±2% of the measured points at N>=2400).
 *   knob:  dur = ar × 2 × t(knob) × 0.95 (PR#384 review, id 4432271415):
 *           the explicit tier bypasses the joint solver's AR-aware n_run
 *           protection VERBATIM, so the all-core contention must go into
 *           the model explicitly — the FULL iteration is golden-prime +
 *           one DUT solve per round (two BDCSVDs in total; the golden
 *           re-roll every kRerollEvery=16 rounds amortizes 1/16 per round
 *           and is not modelled), each eating the AR slowdown. This is
 *           isomorphic to the gemm fix (f6783077) and to the joint
 *           solver's own iteration model (per_solve =
 *           run_budget/(ar×2)). ar = the memory-bound family table
 *           value (the family the auto branch's ar_fam uses; measured
 *           worst-child AR≈39 on the single-memory-node host class vs
 *           kill tolerance AR>~2.4 under the old 0.95×t-only model);
 *           workers == 1 takes ar = 1 — the table value is a FULL-CORE
 *           figure and a lone worker contends only with itself, so the
 *           ungated table value would stretch a -n 1 explicit run to
 *           ~ar×t(knob) (breaking the one-iteration semantics of the
 *           standard `-t … -n 1` regression lane). The AUTO branch keeps
 *           the t(n_hi)×0.95 model: its AR protection is the solver's
 *           own AR-aware n_run (run_budget=140 s tier, measured worst
 *           ~213 s — ~25% inside the 300 s hard grace), and n_run pins
 *           child n on the time side on this host class.
 *   min:   the knob tier ALSO writes test->minimum_duration = ar×2×t(knob)
 *           (no 0.95 margin — the floor of "at least one full iteration";
 *           PR#384 review, id 4432271419): the framework-level -t override
 *           replaces desired_duration unconditionally, so without the
 *           min clamp `-t 2000 -O …mdim=<big>` sits on the 300 s floor
 *           and is SIGQUIT-killed mid-iteration. The AUTO branch writes
 *           NO min: the standard `-t 2000 -n 1` smoke lane must stay
 *           seconds-fast (the auto single iteration is designed inside
 *           the 300 s grace by run_budget=140 s), and at -n 1 n_hi hits
 *           MDIM_MAX, so an auto min would stretch the smoke to the
 *           t(6000) minutes scale.
 *
 * Child n <= n_hi holds for the AUTO branch only: the child returns
 * min(n_mem, n_run, hi), n_mem uses
 * the same budget/c/worker-scaled threads, and its most-conservative
 * AR(25) keeps n_run below the memory ceiling on this host class.
 * An explicit knob/env is applied VERBATIM (dim = knob, no min against
 * n_hi — issue #352), so the duration model must follow the knob too:
 * with n_hi alone, every knob above n_hi times out at the 300 s hard
 * grace (5×t(n_hi)×0.95+30 s < one full 2×t(knob) iteration; e.g.
 * knob=4400 single-threaded: 300 s vs ~487 s measured model) and the
 * child is SIGQUIT-killed mid-iteration — the exact functional
 * regression the pre-reinit code's knob-scaled timeout prevented.
 * (Correction of an earlier comment that claimed a host with fewer
 * threads "only shrinks n_hi — the safe direction": that was backwards.
 * A hard-coded 127 makes the child's n_mem denominator SMALLER than
 * n_hi's on sub-127-worker hosts, so child n can EXCEED n_hi by up to
 * sqrt(127/workers) — dur then UNDER-estimates the real iteration and
 * the derived timeout 5×duration+30 s (300 s floor) loses its headroom,
 * which is the UNSAFE direction, the very P0 timeout mode this PR
 * fixes. Using the actual worker count restores the invariant on every
 * host; the child's own n_run still bounds one iteration at ~140 s
 * (模型, run_budget_ms=140000) / ~213 s (实测最坏) as a second belt.)
 */
static int size_matrix_preinit(struct test *test)
{
    /* 最保守 AR(25) + RSS 表 c 推 n 上界, 再推 duration 上界:
     * child 精算 n 恒 <= 此上界(spec §4.5)。c 引用表函数而非字面量
     * (0.2055)——GEMM_F64 表值已实测重标定过一次(0.0290→0.0315),
     * 字面量会静默陈旧; 分母用实际全机 worker 数而非参考机 127,
     * 子进程 n_mem 的分母是同一 worker 口径(折算到节点), 硬编码 127
     * 在 worker<127 的主机上使 child n 可超 n_hi 达 √(127/workers)。 */
    double budget_kb = (double)sdc_budget_bytes(650) / 1024.0;
    double c_kb = sdc_rss_table_c(SDC_RSS_BDCSVD_C128);
    int workers = sdc_total_threads();
    if (workers < 1)
        workers = 1;
    if (c_kb <= 0.0)
        c_kb = 0.2055;   /* 防御: 表缺失时退回实测字面量口径 */
    int n_hi = (int)std::sqrt(budget_kb / ((double)workers * c_kb));
    if (n_hi > MDIM_MAX) n_hi = MDIM_MAX;
    if (n_hi < MDIM_MIN) n_hi = MDIM_MIN;

    /* 显式 knob/env 档(issue #352): child 对显式 mdim 逐字采用
     * (dim = knob, 不与 n_hi 取 min), duration 模型必须跟着 knob 缩放,
     * 否则任何 knob > n_hi 的显式大维度档都落在 300 s 硬宽限
     * (5×t(n_hi)×0.95+30 s 远小于一次 2×t(knob) 完整迭代) 被
     * SIGQUIT 误杀——迁移前 preinit 的 timeout 恰是随 knob 缩放的,
     * 此处恢复该契约。读取通道经 sdc_knob_or_env_clamped 单一实现,
     * 与 child 恒相同(PR#384 检视, 意见 4432271425: 此前 preinit+child
     * 四份逐字拷贝纯靠手工同步, 任一侧单独改动即静默重开误杀窗口)。
     *
     * 【PR#384 检视, 意见 4432271415】显式档的 duration 必须按全核
     * 全迭代 ar×2×t(knob) 建模: 一次 run 侧迭代 = golden 首算 1 次 +
     * DUT 每轮求解 1 次, 共 2 次 BDCSVD(golden 重算每 kRerollEvery=16
     * 轮才摊 1 次, 未计入), 全核下每次都吃 AR 争抢——与 gemm 修复
     * (f6783077)及联合求解自身的迭代模型(per_solve = run_budget/
     * (ar×2))同构。【R6 勘误, 意见 4463986208】原文「golden 首算 +
     * DUT 两次 BDCSVD」把构成写成 3 次分解, 与 sandstone_eigen_common.h
     * run() 的实际(入口 prime 1 次 + 每 do-while 轮 DUT 1 次)不符
     * ——模型系数 ×2 = 总数 2 次, 数值自始正确, 错的只是构成描述
     * (本块与文件头模型注释、spec §4.5 三处同步修正)。
     * 只乘 0.95×t(knob) 时 timeout = 4.75×t(knob)+30 s, kill 条件
     * AR_real > ~2.4, 而 sve_probe_and_init 的 run_budget_ms 注释实测
     * 单内存节点最坏 child 有效 AR≈39——多 worker 显式档必被误杀,
     * #352 的失败模式只对 -n 1 真正闭合。三个口径:
     *   - ar 取内存密集族表值(与本测试 auto 分支的 ar_fam 同族);
     *   - workers == 1 时取 1: AR 表值是全核口径, 单 worker 自争抢
     *     为 1(物理定义); 不折算则 -n 1 显式档裸跑 target 被拉到
     *     ~ar 倍 t(knob), 标准回归路径(-t … -n 1)的单迭代语义破坏;
     *   - auto 分支维持 t(n_hi)×0.95(P0-1 §4.5 原模型): 其 AR 保护
     *     来自联合求解 AR-aware 的 n_run(run_budget=140 s 档, 实测
     *     最坏 ~213 s, 距 300 s floor 留 ~25% 裕量), 且 n_run 在本
     *     host class 恒把 child n 压在时间侧——显式档恰恰绕过这层
     *     保护, 才必须把 AR 显式放进模型。 */
    int64_t knob = sdc_knob_or_env_clamped(test, "mdim", MDIM_MIN, MDIM_MAX);

    double iter_s;
    if (knob > 0) {
        double ar = workers > 1
                ? sdc_ar_factor(SDC_FAM_MEM_BOUND, sdc_numa_probe()) : 1.0;
        iter_s = ar * 2.0
               * (243.4 * std::pow((double)knob / 4400.0, 3.0) + 1.0);
        /* 【PR#384 检视 R7, 意见 4464199547】+1.0 系大 N 定标的拟合
         * 常数, 在此随整个 t(N) 一并乘进 ar×2, 与 auto 分支(desired
         * 上界模型, 常数不放大)口径不同——后果方向保守(地板更高),
         * 如实记录为已知口径差: 小 knob 档 min 偏离紧致物理下限
         * ~3×(mdim=600 -n 1: min 3234ms vs 实测内层单迭代 0.92-1.1s;
         * -n 2 的 80859ms 中 50s 系 +1×ar×2=50 的常数通胀), 大 knob
         * 档可忽略(4400 档 +1 占 0.4%)。与二值闸门裁定(4439402800/
         * 4440012653, 保守方向)一致, 不改模型。 */
        /* 【PR#384 检视, 意见 4432271419】-t 在框架层无条件覆盖
         * desired_duration(sandstone_run.cpp test_duration 的
         * sApp->test_time 分支), 而本测试此前未设 minimum_duration →
         * 该夹钳空置——`-t 2000 -O …mdim=<大>` 的 target 被钉在 2 s,
         * timeout 落到 max(5×2+30, 300) = 300 s floor, 单次全迭代
         * (2×t(knob) ≫ 300 s)被 SIGQUIT 误杀(修复前实测: -t 2000 -n 1
         * -O mdim=4000 → 320.6 s 处 SIGQUIT)。把单次全迭代模型(无
         * 0.95 裕量: min 是"至少跑完一次迭代"的物理下限)写进
         * minimum_duration, -t 小值档的 target 被夹钳到单迭代,
         * timeout(5×min+30)随之随 knob 缩放。auto 分支不写:
         * `-t 2000 -n 1` 标准冒烟必须保持秒级(auto 单迭代由
         * run_budget=140 s 设计收在 300 s floor 内), 且 -n 1 下 n_hi
         * 撞 MDIM_MAX, 写 min 会把冒烟拉到 t(6000) 分钟级。 */
        /* 【PR#384 检视 R6, 意见 4463986219】SVD 侧不加 GEMM 的
         * GEMM_AR_CAVEAT_X(3×)加权——量化账在本文件镜像(完整裁定
         * 记录: gemm_double_max_arm.cpp 的 minimum_duration 注释块 +
         * spec §4.5 R3/R4 块): 本测试 mem 族表值 25 实测低估仅
         * 1.56×(单内存节点最坏 child 有效 AR≈39, 远小于 GEMM 的
         * 3×), SVD VL=128 档因子实测 1.064×(2026-11-04, -n 1 -O
         * mdim=2048 单迭代 56.06s→59.66s, SDCSHIELD_ARM64_SPEC_MAX_VL
         * =128 原生降档), 代入裕量 5×25/(39×1.064×1.02)≈2.95×, 打穿
         * 需档因子 ≥125/(39×1.02)≈3.14×(裕量=阈值/实测档因子, 同
         * 一量; 【R7 勘误, 意见 4464199557】R4 原记 ≈3.1×/3.15×/
         * 2.96× 系算术误差: 125/42.33=2.95, 125/39.78=3.14); 加 3×
         * 会把 4440012653 已裁定的中间档 min 虚抬成本再放大 3 倍
         * 且无实测支撑, 维持不加。调本测试 ar 表值/幂律系数时须
         * 对照本账重算。【R8, 意见 4464388852】本账系三处镜像之一
         * (本块 / gemm CAVEAT 块 SVD 对照句 / spec §4.5 R3/R4/R7
         * 块), 单一真源以 spec 为准——注释无编译期机制钉住, 改账
         * 须三处同步(R6 补镜像、R7 勘误两个提交已实证失同步风险);
         * 把账本常数化为 constexpr/static_assert 的机制化钉住属
         * 框架级设计项, 超出本 PR 边界。 */
        test->minimum_duration = (int)(iter_s * 1000.0);   /* ms */
    } else {
        iter_s = 243.4 * std::pow((double)n_hi / 4400.0, 3.0) + 1.0;
    }
    /* 【PR#384 检视 R5, 意见 4463650400】显式档生效侧澄清: 同一 iter_s
     * 下本 desired(0.95×iter_s)恒小于上方 min(1.0×iter_s), 而框架
     * test_duration 的 min 夹钳最后执行(sandstone_run.cpp:1879-1880)
     * → 显式档的 target/timeout 恒由 min 决定, 本 desired 在显式档是
     * 模型记录值(时间预算目标), 单独调它不改显式档时长(须调 min)。
     * auto 档不写 min, desired 才是生效目标——两档共用本行, "-5%
     * margin" 仅对 auto 档是真实生效裕量。 */
    test->desired_duration = (int)(iter_s * 950.0);   /* ms */
    return EXIT_SUCCESS;
}

/*
 * Gate SVE availability via the framework layer (all-VL Phase 2 P5):
 * arm64_require_sve_vl probes HWCAP_SVE and reads rdvl — no SVE
 * instructions execute on the no-SVE path. We must not let any
 * SVE-instrumented Eigen code run on a CPU without SVE (it would
 * SIGILL), so this stays before the Eigen-backed init's allocations;
 * the framework's compiler_minimum_device gate already skips non-SVE
 * hosts before init — this keeps a test-specific reason if that
 * ordering ever changes.
 */
static int sve_probe_and_init(struct test *test)
{
    const long svl = arm64_require_sve_vl(test, 128, 1024);
    if (svl < 0)
        return EXIT_SKIP;

    /* The framework pinned the control thread before this aux thread was
     * created, so `svl` is the tier the workers will run at. VALIDATE the
     * tier before anything else: the joint solver's probe below executes
     * that tier's fixed-width Eigen packets on THIS thread, and make_data
     * allocates the variant for it; test_run compares the worker's
     * readback against this value and fails closed on any divergence
     * instead of reinterpreting objects built for another tier.
     * (svd_tier_select: generated by EIGEN_SVE_DEFINE_DISPATCHERS in
     * sandstone_eigen_sve_dispatch.h — the tier whitelist this TU used to
     * spell out by hand.) */
    if (!svd_tier_select(test, svl))
        return EXIT_SKIP;

    /* Dimension (P0-1, spec §4.5): knob > env > joint-solver auto, all in
     * the CHILD so exec_each_test images size themselves. The auto branch
     * probes solve_once on THIS thread (its VL is the tier just recorded)
     * and returns min(n_mem, n_run): per-NUMA-node memory budget against
     * the measured complex-BDCSVD RSS coefficient, and a full-core
     * single-iteration budget via the power-law fit and the memory-bound
     * AR factor. quick mode collapses to MDIM_MIN.
     *
     * run_budget_ms deviates from the joint contract value 200000 (= 300 s
     * hard grace × 0.67): the measured WORST-child slowdown on a
     * single-memory-node host exceeds the AR table's 1-node mem-bound
     * entry (25). Measured 2026-10-27, 127 threads, n=1100 (~31 GiB
     * footprint): the node-0 (local-DRAM) children finish while the
     * children on the memory-less nodes (remote DRAM) see an effective AR
     * of ~39 — 1.55×, just past the 1.5× margin the 0.67 factor embeds.
     * With 200000 the solver picked n≈1229 and the remote children could
     * not finish one iteration inside the 300 s grace (SIGQUIT at
     * 304-314 s, reproduced twice). 140000 lands n_run ≈ 1050-1095
     * (n=1100 measured 228 s wall including init), i.e. ~225 s total —
     * inside the grace with ~25 % margin, and within the plan's expected
     * [750, 1100]. The principled fix is the AR table entry itself
     * (framework/sdc_numa.cpp — Task 1 scope, flagged to the
     * coordinator); this per-test budget is the in-scope compensation
     * and should be revisited when the table is re-calibrated.
     * (注: n=1100 是定点实验档; auto 档在同一 run_budget_ms 下实测最坏
     * ~213 s, 见上方 size_matrix_preinit 注释, 两个口径不矛盾.) */
    int dim;
    int64_t knob = sdc_knob_or_env_clamped(test, "mdim", MDIM_MIN, MDIM_MAX);
    if (knob > 0) {
        dim = (int)knob;
    } else {
        struct sdc_joint_args ja = {
            .lo = MDIM_MIN, .hi = MDIM_MAX,
            .fam = SDC_RSS_BDCSVD_C128,    /* 0.2055 KB/n²/thread, measured */
            .bytes_per_elem = 16, .matrices_per_thread = 1, .rss_ratio = 12.0,
                    /* legacy triple (pre-table model), ignored while fam
                     * selects the RSS table */
            .shared_bytes_per_slice = 0,   /* make_data holds no matrices */
            .mem_fraction_permille = 650,
            .ar_fam = SDC_FAM_MEM_BOUND,
            .run_budget_ms = 140000,       /* worst-child iteration budget;
                                            * 140 s at the table AR=25 ≈
                                            * 218 s at the measured
                                            * worst-child AR≈39 (see above) */
        };
        try {
            dim = sdc_joint_dim_slice(test, "mdim", &ja, svd_solve_once);
        } catch (...) {
            /* probe allocation failure (transient OOM &c): fall back to
             * the floor — same doctrine as the SVD template's calibrated
             * path ("上限宁小勿大"): a sizing probe must never terminate
             * the child. */
            log_warning("[联合求解] %s: mdim 探针异常 → 退守下限 %d",
                        test->id, MDIM_MIN);
            dim = MDIM_MIN;
        }
    }

    /* 【PR#384 检视 R5, 意见 4463650411】exec_each_test child 是全新
     * exec 镜像: preinit 只在 parent 跑(sandstone.cpp 的 -x 分支在
     * 主流程 preinit_tests 之前 return), 本进程 test 结构两字段恒
     * 静态初值 0——照常打印会被误读为"无下限保护", 而生效的 -t/min
     * 夹钳经 parent 的 test_duration → shmem->current_test_endtime
     * 传入(R3 意见 4440012682 勘误: fork/exec 迭代语义一致)。判据:
     * preinit 成功后 desired_duration 恒 > 0(两分支 iter_s > 0),
     * == 0 即 exec child。 */
    if (test->desired_duration > 0) {
        /* 【PR#384 检视 R6, 意见 4463986196】min 的文案随值走: auto 档
         * 设计不写 min(0 = 无下限, -t/默认时长直接生效——4432271419
         * 的 -t 夹钳仅显式档有), 显式档才有单迭代下限, 恒 0 配显式档
         * 文案是值/标签双重错配。 */
        log_info("M_DIM %d (sized in child init: knob/env, else 联合求解 "
                 "min(n_mem, n_run); preinit desired_duration %d ms, "
                 "minimum_duration %d ms (%s); "
                 "override with -O eigen_svd_cdouble_sve.mdim=N)",
                 dim, test->desired_duration, test->minimum_duration,
                 test->minimum_duration > 0
                     ? "显式档: 单迭代下限, -t 夹钳"
                     : "auto 档: 设计不设下限, -t/默认时长直接生效");
    } else {
        log_info("M_DIM %d (sized in child init: knob/env, else 联合求解 "
                 "min(n_mem, n_run); exec_each_test child: 本进程未跑 "
                 "preinit, desired/minimum_duration 恒 0——生效的 -t/min "
                 "夹钳经 parent shmem 传入, 非无下限保护; "
                 "override with -O eigen_svd_cdouble_sve.mdim=N)",
                 dim);
    }

    /* Allocate the test data (the runtime-dimension template's run()
     * primes its own per-thread matrices; the init-time golden BDCSVD
     * became dead computation once run() stopped reading eigen_test_data's
     * matrices — removed. Timing note: desired_duration now covers exactly
     * the two run-side decompositions (prime + DUT); init no longer
     * contributes a third. svd_make_data routes to the tier recorded by
     * svd_tier_select — generated by EIGEN_SVE_DEFINE_DISPATCHERS in
     * sandstone_eigen_sve_dispatch.h.) */
    test->data = svd_make_data(dim);
    return EXIT_SUCCESS;
}

/*
 * Per-tier run wrapper (design §4.7): re-read and re-pin THIS worker to
 * the framework-chosen tier, verify the readback equals both the pin and
 * the tier test_init allocated for, then dispatch to that tier's payload.
 * The framework pinned the control thread before init (so init saw the
 * same tier); the re-pin here is an idempotent second check that a silent
 * environment downgrade cannot slip a fixed-width packet onto the wrong
 * VL. The readback uses arm64_sve_vl_bytes() (.inst-encoded rdvl), NOT
 * svcntb(): in a -msve-vector-bits TU GCC constant-folds svcntb(), while
 * the raw rdvl reads the actual per-thread runtime VL.
 * (svd_run: generated by EIGEN_SVE_DEFINE_DISPATCHERS in
 * sandstone_eigen_sve_dispatch.h — the wrapper body migrated there
 * verbatim 2026-11-02; only the log line changed to the unified
 * "Eigen SVE variant = <bits>-bit" form.)
 */
static int eigen_svd_cdouble_sve_run(struct test *test, int cpu)
{
    return svd_run(test, cpu);
}

/* DECLARE_TEST needs a plain function symbol: one-line wrapper around the
 * generated svd_cleanup (per-tier cleanup switch lives in
 * sandstone_eigen_sve_dispatch.h; the generated function returns void). */
static int eigen_svd_cdouble_sve_cleanup(struct test *test)
{
    svd_cleanup(test);
    return EXIT_SUCCESS;
}

